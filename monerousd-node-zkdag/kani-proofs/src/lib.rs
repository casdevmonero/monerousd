#[cfg(kani)]
mod solvency_proofs {
    use crate::solvency_arith::*;

    fn any256() -> U256 {
        [kani::any(), kani::any(), kani::any(), kani::any()]
    }

    /// A `U256` as its exact `(hi, lo)` u128 halves — the reference the limb loops are measured against.
    fn halves(a: U256) -> (u128, u128) {
        ((u128::from(a[3]) << 64) | u128::from(a[2]), (u128::from(a[1]) << 64) | u128::from(a[0]))
    }

    /// ⛔ add256 is the exact 256-bit sum, or `None` exactly when that sum passes 2^256 — never a wrapped total.
    #[kani::proof]
    #[kani::unwind(5)]
    fn add256_is_the_exact_sum_or_refuses() {
        add_law(add256, any256(), any256());
    }

    /// The exactness law, applied to the shipping `add256` and to its planted mutant alike.
    fn add_law(add: fn(U256, U256) -> Option<U256>, a: U256, b: U256) {
        let ((ah, al), (bh, bl)) = (halves(a), halves(b));
        let (lo, c) = al.overflowing_add(bl);
        let (h1, c1) = ah.overflowing_add(bh);
        let (hi, c2) = h1.overflowing_add(u128::from(c));
        match add(a, b) {
            None => assert!(c1 || c2),
            Some(s) => assert!(!(c1 || c2) && halves(s) == (hi, lo)),
        }
    }

    /// ⛔ sub256 is the exact difference, or `None` exactly when `a < b` — never a release past what is held.
    #[kani::proof]
    #[kani::unwind(5)]
    fn sub256_is_the_exact_difference_or_refuses() {
        let (a, b) = (any256(), any256());
        let ((ah, al), (bh, bl)) = (halves(a), halves(b));
        let (lo, br) = al.overflowing_sub(bl);
        let (h1, b1) = ah.overflowing_sub(bh);
        let (hi, b2) = h1.overflowing_sub(u128::from(br));
        match sub256(a, b) {
            None => assert!(b1 || b2),
            Some(d) => assert!(!(b1 || b2) && halves(d) == (hi, lo)),
        }
    }

    /// ge256 is the 256-bit order — the comparison every solvency and backing check decides by.
    #[kani::proof]
    #[kani::unwind(5)]
    fn ge256_is_the_256_bit_order() {
        let (a, b) = (any256(), any256());
        assert_eq!(ge256(a, b), halves(a) >= halves(b));
    }

    /// A redeem that applies conserves both totals exactly and never releases more than it burns.
    #[kani::proof]
    #[kani::unwind(5)]
    fn an_applied_peg_out_conserves_and_never_releases_more_than_it_burns() {
        let (r, m, rel, burn): (u128, u128, u128, u128) = (kani::any(), kani::any(), kani::any(), kani::any());
        if let Some((nr, nm)) = peg_out_apply(r, m, rel, burn, kani::any()) {
            assert!(rel <= burn && nr.checked_add(rel) == Some(r) && nm.checked_add(burn) == Some(m));
        }
    }

    /// mul256_small is the exact 256-bit product by a u64 scale, or `None` exactly when it passes 2^256.
    #[kani::proof]
    #[kani::unwind(5)]
    fn mul256_small_is_the_exact_product_or_refuses() {
        let (a, k): (U256, u64) = (any256(), kani::any());
        let k = u128::from(k);
        let ((ah, al), m) = (halves(a), u128::from(u64::MAX));
        // schoolbook over 64-bit digits: each digit·k < 2^128, carries folded one digit at a time
        let digits = [al & m, al >> 64, ah & m, ah >> 64];
        let (mut out, mut carry) = ([0u128; 4], 0u128);
        for i in 0..4 {
            let p = digits[i] * k + carry; // < 2^128: (2^64−1)² + (2^64−1) < 2^128
            out[i] = p & m;
            carry = p >> 64;
        }
        match mul256_small(a, k as u64) {
            None => assert!(carry != 0),
            Some(p) => assert!(carry == 0 && halves(p) == ((out[3] << 64) | out[2], (out[1] << 64) | out[0])),
        }
    }

    /// The u128 peg-in and the u256 peg-in are ONE rule: both apply `mul256_small`/`ge256` to the same embedded
    /// operands (proven above), so they can differ only in the totals' sums — and the embedding commutes with
    /// addition: a u128 sum that fits is the u256 sum, and one that does not still fits u256 (the narrow form
    /// refuses it, fail-closed). Stated whole, the twin re-solves two copies of one multiplier and timed out at 300 s
    /// (scratchpad/verify/kani-solv-2/); this is the lemma it reduces to.
    #[kani::proof]
    #[kani::unwind(5)]
    fn embedding_u128_in_u256_commutes_with_add() {
        let (a, b): (u128, u128) = (kani::any(), kani::any());
        let s = add256(u256_from_u128(a), u256_from_u128(b));
        match a.checked_add(b) {
            Some(t) => assert!(s.is_some_and(|s| halves(s) == (0, t))),
            None => assert!(s.is_some_and(|s| halves(s) == (1, a.wrapping_add(b)))),
        }
    }

    /// PLANTED: the final carry dropped — a 256-bit overflow wraps to a small total instead of refusing.
    fn add256_wrapping(a: U256, b: U256) -> Option<U256> {
        let mut out = [0u64; 4];
        let mut carry = 0u128;
        for i in 0..4 {
            let s = u128::from(a[i]) + u128::from(b[i]) + carry;
            out[i] = s as u64;
            carry = s >> 64;
        }
        Some(out)
    }

    #[kani::proof]
    #[kani::unwind(5)]
    #[kani::should_panic]
    fn refuter_a_wrapping_add256_is_caught() {
        add_law(add256_wrapping, any256(), any256());
    }

    /// PLANTED: limbs compared least-significant first — the order a backing check would decide by is wrong.
    fn ge256_low_first(a: U256, b: U256) -> bool {
        for i in 0..4 {
            if a[i] != b[i] {
                return a[i] > b[i];
            }
        }
        true
    }

    #[kani::proof]
    #[kani::unwind(5)]
    #[kani::should_panic]
    fn refuter_a_low_first_ge256_is_caught() {
        let (a, b) = (any256(), any256());
        assert_eq!(ge256_low_first(a, b), halves(a) >= halves(b));
    }
}

#[cfg(kani)]
mod quorum_proofs {
    use crate::quorum_math::*;

    /// `x · k` for a small `k`, exactly, as a 256-bit `(hi, lo)` pair — the law's arithmetic, never saturating.
    fn wide(x: u128, k: u128) -> (u128, u128) {
        let (lo_part, mid) = ((x & u128::from(u64::MAX)) * k, (x >> 64) * k); // each < 2^66
        let (lo, carry) = (mid << 64).overflowing_add(lo_part);
        ((mid >> 64) + u128::from(carry), lo)
    }

    /// ⛔ THE QUORUM LAW over every (weight, total) in u128: ≥ 2/3 ⇔ 3·weight ≥ 2·total in exact arithmetic, and never
    /// with no bond.
    #[kani::proof]
    fn two_thirds_met_is_exactly_three_weight_at_least_two_total() {
        let (w, t): (u128, u128) = (kani::any(), kani::any());
        assert_eq!(two_thirds_met(w, t), t > 0 && wide(w, 3) >= wide(t, 2));
    }

    /// DB-387's strict threshold: > 2/3 ⇔ 3·weight > 2·total, exactly.
    #[kani::proof]
    fn more_than_two_thirds_is_exactly_three_weight_above_two_total() {
        let (w, t): (u128, u128) = (kani::any(), kani::any());
        assert_eq!(more_than_two_thirds(w, t), t > 0 && wide(w, 3) > wide(t, 2));
    }

    /// R3 — the shown takeover cost is the custody tally's own inverse: `least_capturing_weight(h)` clears ≥ 2/3 alone
    /// against `h`, and one unit less does not (every `h` whose `3h` fits; the ledger's bonds sit far below).
    #[kani::proof]
    fn least_capturing_weight_is_the_two_thirds_tallys_exact_inverse() {
        let h: u128 = kani::any();
        kani::assume(h <= u128::MAX / 3);
        let c = least_capturing_weight(h);
        assert!(two_thirds_met(c, h + c));
        assert!(c == 1 || !two_thirds_met(c - 1, h + c - 1));
    }

    /// PLANTED: the six sites' old form — the right side saturates past u128::MAX / 2 and about half the bond clears.
    #[kani::proof]
    #[kani::should_panic]
    fn refuter_a_saturating_quorum_is_caught() {
        let (w, t): (u128, u128) = (kani::any(), kani::any());
        let old = t > 0 && w.saturating_mul(3) >= t.saturating_mul(2);
        assert_eq!(old, t > 0 && wide(w, 3) >= wide(t, 2));
    }

    /// PLANTED: an off-by-one (⌊2t/3⌋ where ⌈2t/3⌉ belongs) clears a tally one unit short of two thirds.
    #[kani::proof]
    #[kani::should_panic]
    fn refuter_an_off_by_one_quorum_is_caught() {
        let (w, t): (u128, u128) = (kani::any(), kani::any());
        let floor_form = t > 0 && w >= t - t.div_ceil(3);
        assert_eq!(floor_form, t > 0 && wide(w, 3) >= wide(t, 2));
    }
}

