#[cfg(kani)]
mod proofs {
    use crate::economics::*;

    /// Small scope: up to 4 symbolic inputs of full u64 width (Jackson's small-scope hypothesis). The cover-width
    /// refusal (> SPEND_MAX_INPUTS) is its own harness at the production width, since its values do not matter.
    const SCOPE: usize = 4;

    /// The law, stated in exact (u128) arithmetic: accepted ⇔ 1..=MAX inputs whose exact sum equals the exact
    /// `out0 + out1 + fee`, and that sum is a u64 amount.
    fn law(v: &[u64], out0: u64, out1: u64, fee: u64) -> bool {
        let mut total: u128 = 0;
        for x in v {
            total += *x as u128;
        }
        let out = out0 as u128 + out1 as u128 + fee as u128;
        !v.is_empty() && v.len() <= SPEND_MAX_INPUTS && total == out && total <= u64::MAX as u128
    }

    fn any_spend() -> ([u64; SCOPE], usize, u64, u64, u64) {
        let n: usize = kani::any();
        kani::assume(n <= SCOPE);
        (kani::any(), n, kani::any(), kani::any(), kani::any())
    }

    #[kani::proof]
    #[kani::unwind(6)]
    fn spend_conserves_accepts_exactly_the_conservation_law() {
        let (v, n, o0, o1, f) = any_spend();
        assert_eq!(spend_conserves(&v[..n], o0, o1, f), law(&v[..n], o0, o1, f));
    }

    #[kani::proof]
    #[kani::unwind(40)]
    fn spend_conserves_refuses_past_the_cover_width() {
        let v = [0u64; SPEND_MAX_INPUTS + 1];
        assert!(!spend_conserves(&v, 0, 0, 0));
        assert!(spend_conserves(&v[..SPEND_MAX_INPUTS], 0, 0, 0));
    }

    /// PLANTED: the input sum wraps (the inflation oracle the real function's `checked_add` refuses).
    fn spend_conserves_wrapping(v: &[u64], out0: u64, out1: u64, fee: u64) -> bool {
        if v.is_empty() || v.len() > SPEND_MAX_INPUTS {
            return false;
        }
        let total = v.iter().fold(0u64, |a, x| a.wrapping_add(*x));
        out0.checked_add(out1).and_then(|o| o.checked_add(fee)) == Some(total)
    }

    /// PLANTED: the fee term is dropped (value destroyed without a burn record).
    fn spend_conserves_no_fee(v: &[u64], out0: u64, out1: u64, _fee: u64) -> bool {
        if v.is_empty() || v.len() > SPEND_MAX_INPUTS {
            return false;
        }
        let total = v.iter().try_fold(0u64, |a, x| a.checked_add(*x));
        total.is_some() && out0.checked_add(out1) == total
    }

    #[kani::proof]
    #[kani::unwind(6)]
    #[kani::should_panic]
    fn refuter_spend_law_catches_a_wrapping_sum() {
        let (v, n, o0, o1, f) = any_spend();
        assert_eq!(spend_conserves_wrapping(&v[..n], o0, o1, f), law(&v[..n], o0, o1, f));
    }

    #[kani::proof]
    #[kani::unwind(6)]
    #[kani::should_panic]
    fn refuter_spend_law_catches_a_dropped_fee() {
        let (v, n, o0, o1, f) = any_spend();
        assert_eq!(spend_conserves_no_fee(&v[..n], o0, o1, f), law(&v[..n], o0, o1, f));
    }

    #[kani::proof]
    fn spend_note_delta_is_two_minus_n() {
        let n: usize = kani::any();
        kani::assume(n <= SPEND_MAX_INPUTS);
        assert_eq!(spend_note_delta(n), 2 - n as i64);
    }

    // ── the retention fee: bounded, fail-safe, and never cheaper for a poorer endowment ──

    #[kani::proof]
    #[kani::solver(cadical)]
    fn retention_fee_stays_inside_its_clamps() {
        let fee = retention_fee_atomic(kani::any(), kani::any(), kani::any());
        assert!((RETENTION_FEE_MIN_ATOMIC..=RETENTION_FEE_MAX_ATOMIC).contains(&fee));
    }

    // FAIL-SAFE, decomposed (the one-harness form recomputed b·r·YEARS beside the function's own product — two 128-bit
    // multipliers to prove equal — and timed out at 300 s, kani-value-3.log). `retention_fee_atomic` IS
    // `retention_fee_of_coverage(coverage_bps(..))` and `coverage_bps` IS `retention_need(..).map(coverage_of_need)`,
    // so the three lemmas below compose to: nothing measurable ⇒ BASE, a drained endowment ⇒ MAX.
    #[kani::proof]
    fn retention_fee_fails_safe() {
        // no measurable coverage holds at BASE, never free; zero coverage charges the MAXIMUM
        assert_eq!(retention_fee_of_coverage(None), RETENTION_FEE_BASE_ATOMIC);
        assert_eq!(retention_fee_of_coverage(Some(0)), RETENTION_FEE_MAX_ATOMIC);
        // a drained endowment covers zero of every nonzero need
        let n: u128 = kani::any();
        kani::assume(n != 0);
        assert_eq!(coverage_of_need(0, n), 0);
    }

    #[kani::proof]
    fn a_need_is_never_zero_and_nothing_retained_or_paid_has_none() {
        let (b, r): (u128, u128) = (kani::any(), kani::any());
        assert_ne!(retention_need(b, r), Some(0));
        assert_eq!(retention_need(0, r), None);
        assert_eq!(retention_need(b, 0), None);
    }

    /// PLANTED: a zero need passed through — the fee would divide a drained reading by nothing.
    fn retention_need_zero_kept(b: u128, r: u128) -> Option<u128> {
        b.checked_mul(r)?.checked_mul(RETENTION_TARGET_COVERAGE_YEARS)
    }

    #[kani::proof]
    #[kani::should_panic]
    fn refuter_zero_need_is_caught() {
        let (b, r): (u128, u128) = (kani::any(), kani::any());
        assert_ne!(retention_need_zero_kept(b, r), Some(0));
    }

    // MONOTONICITY, in two lemmas (the four-way symbolic u128 division timed out at 300 s as one harness,
    // scratchpad/verify/kani-value-1.log). `retention_fee_atomic` reads the endowment ONLY through `coverage_bps`, so
    // (a) coverage never falls as the endowment grows, for every (bytes, rate), and (b) the fee never rises as coverage
    // grows — at need = 10,000 (bytes 500, rate 1) coverage equals the endowment, so (b) ranges over every coverage —
    // together give "a poorer endowment is never charged less".
    // (a) as EXACTNESS, one division (the two-call relational form timed out at 300 s, kani-value-2.log): coverage is
    // exactly floor(sat(e·BPS) / need), and sat(e·BPS) never falls as e grows, so neither does the floor.
    // Decomposed: the need's product is computed ONCE (`retention_need`), so the exactness law is over a free nonzero
    // need — one divider, no second multiplier to match (the recomputing form timed out at 300 s, kani-value-3.log).
    // CaDiCaL times out at 300 s on the symbolic u128 divider (scratchpad/verify/kani-decomp-1/); Kissat proves it in
    // 94.8 s (scratchpad/verify/kani-open-kissat-1.log). Bitwuzla (CBMC's SMT2 path) reports spurious FAILs here — its
    // counterexamples satisfy the law when replayed in plain Rust (kani-playback-pendulum.log) — never a proof backend.
    #[kani::proof]
    #[kani::solver(kissat)]
    fn coverage_is_exactly_the_floor_of_the_saturated_endowment_over_the_need() {
        let (e, n): (u128, u128) = (kani::any(), kani::any());
        kani::assume(n != 0);
        let cov = coverage_of_need(e, n);
        let sat = e.saturating_mul(BPS);
        let lo = cov.checked_mul(n).expect("cov·need ≤ sat");
        assert!(lo <= sat && sat - lo < n);
    }

    // (b) split at coverage 2^17 (still timed out at 300 s as one harness over all u128, kani-value-2.log): below it the
    // high bits are pinned to zero and the divider collapses; above it 10^8 / c ≤ 762 < MIN, so the fee IS the floor —
    // and every fee is ≥ the floor (`retention_fee_stays_inside_its_clamps`), so c1 ≤ 2^17 < c2 needs no third harness.
    const SPLIT: u128 = 1 << 17;

    #[kani::proof]
    #[kani::solver(cadical)]
    fn retention_fee_never_rises_as_coverage_grows_below_the_split() {
        let (c1, c2): (u128, u128) = (kani::any(), kani::any());
        kani::assume(c1 <= c2 && c2 <= SPLIT);
        assert_eq!(coverage_bps(c1, 500, 1), Some(c1));
        assert!(retention_fee_atomic(c1, 500, 1) >= retention_fee_atomic(c2, 500, 1));
    }

    #[kani::proof]
    #[kani::solver(cadical)]
    fn retention_fee_is_the_floor_above_the_split() {
        let c: u128 = kani::any();
        kani::assume(c > SPLIT);
        assert_eq!(retention_fee_atomic(c, 500, 1), RETENTION_FEE_MIN_ATOMIC);
    }

    /// PLANTED: the clamp is dropped.
    fn retention_fee_unclamped(e: u128, b: u128, r: u128) -> u128 {
        let Some(cov) = coverage_bps(e, b, r) else {
            return RETENTION_FEE_BASE_ATOMIC;
        };
        if cov == 0 {
            return RETENTION_FEE_MAX_ATOMIC;
        }
        RETENTION_FEE_BASE_ATOMIC.saturating_mul(BPS) / cov
    }

    #[kani::proof]
    #[kani::should_panic]
    fn refuter_retention_clamp_is_caught() {
        let fee = retention_fee_unclamped(kani::any(), kani::any(), kani::any());
        assert!((RETENTION_FEE_MIN_ATOMIC..=RETENTION_FEE_MAX_ATOMIC).contains(&fee));
    }

    // ── the no-issuance payout law ──

    #[kani::proof]
    fn a_payout_is_applied_exactly_or_refused() {
        let (e, p): (u128, u128) = (kani::any(), kani::any());
        match endowment_after_payout(e, p) {
            Some(after) => assert_eq!(after.checked_add(p), Some(e)),
            None => { assert!(p > e) }
        }
        assert_eq!(payout_is_funded(e, p), p <= e);
    }

    /// ⛔ "what the creator pays equals what the endowment receives" — exactly, never up to a saturation.
    #[kani::proof]
    fn retention_fee_conserves_is_exact() {
        let (paid, before, after): (u128, u128, u128) = (kani::any(), kani::any(), kani::any());
        assert_eq!(retention_fee_conserves(paid, before, after), before.checked_add(paid) == Some(after));
    }

    /// PLANTED: the payout saturates instead of refusing (an unfunded payout applied, the difference minted).
    #[kani::proof]
    #[kani::should_panic]
    fn refuter_payout_saturation_is_caught() {
        let (e, p): (u128, u128) = (kani::any(), kani::any());
        let after = e.saturating_sub(p);
        assert_eq!(after.checked_add(p), Some(e));
    }
}

