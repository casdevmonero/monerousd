// §BR-0 — PEG WITHDRAWAL FEE CURVE (`peg_arith::withdrawal_fee_bps`)
// Laws: bounded, monotone non-decreasing in draw, convex (u² term), and
// planted refuters for each.
// ═══════════════════════════════════════════════════════════════════════════════
#[cfg(kani)]
mod peg_fee_proofs {
    use crate::peg_arith::*;

    // ── Law 1: result is ALWAYS in [min_bps, max_bps] (clamped to 10_000) ──

    #[kani::proof]
    fn fee_is_bounded_in_the_governance_band() {
        let (r, d): (u128, u128) = (kani::any(), kani::any());
        let (lo, hi): (u32, u32) = (kani::any(), kani::any());
        let fee = withdrawal_fee_bps(r, d, lo, hi);
        let hi_eff = hi.min(10_000);
        let lo_eff = lo.min(hi_eff);
        assert!(fee >= lo_eff);
        assert!(fee <= hi_eff);
    }

    /// PLANTED: drop the clamp on max_bps — the fee can exceed 10_000.
    fn fee_unclamped_max(r: u128, d: u128, lo: u32, hi: u32) -> u32 {
        let min_bps = lo.min(hi);
        if r == 0 { return hi; }
        let u_bps = d.min(r).saturating_mul(10_000) / r;
        let u_sq = u_bps.saturating_mul(u_bps) / 10_000;
        let span = (hi - min_bps) as u128;
        (min_bps as u128 + span.saturating_mul(u_sq) / 10_000) as u32
    }

    #[kani::proof]
    #[kani::should_panic]
    fn refuter_unclamped_max_is_caught() {
        let (r, d): (u128, u128) = (kani::any(), kani::any());
        let (lo, hi): (u32, u32) = (kani::any(), kani::any());
        let fee = fee_unclamped_max(r, d, lo, hi);
        assert!(fee <= 10_000);
    }

    // ── Law 2: monotone non-decreasing in draw_units (fixed reserve) ──

    #[kani::proof]
    fn fee_is_monotone_in_draw() {
        let r: u128 = kani::any();
        let (d1, d2): (u128, u128) = (kani::any(), kani::any());
        kani::assume(d1 <= d2);
        let (lo, hi): (u32, u32) = (kani::any(), kani::any());
        assert!(withdrawal_fee_bps(r, d1, lo, hi) <= withdrawal_fee_bps(r, d2, lo, hi));
    }

    /// PLANTED: LINEAR instead of convex — `u` not `u²`. Same band, different shape: for u in (0,1)
    /// the linear fee exceeds the convex one at low utilization, so a draw that the convex curve
    /// under-charges becomes an observable difference (the refuter finds it or it is not convex).
    fn fee_linear(r: u128, d: u128, lo: u32, hi: u32) -> u32 {
        let hi = hi.min(10_000);
        let lo = lo.min(hi);
        if r == 0 { return hi; }
        let u_bps = d.min(r).saturating_mul(10_000) / r;
        let span = (hi - lo) as u128;
        (lo as u128 + span.saturating_mul(u_bps) / 10_000) as u32
    }

    #[kani::proof]
    #[kani::should_panic]
    fn refuter_linear_differs_from_convex() {
        let r: u128 = kani::any();
        kani::assume(r > 0);
        let d: u128 = kani::any();
        let fee_c = withdrawal_fee_bps(r, d, WITHDRAW_FEE_MIN_BPS, WITHDRAW_FEE_MAX_BPS);
        let fee_l = fee_linear(r, d, WITHDRAW_FEE_MIN_BPS, WITHDRAW_FEE_MAX_BPS);
        assert_eq!(fee_c, fee_l);
    }

    // ── Law 3: empty reserve returns max_bps (clamped) ──

    #[kani::proof]
    fn empty_reserve_returns_max() {
        let d: u128 = kani::any();
        let (lo, hi): (u32, u32) = (kani::any(), kani::any());
        assert_eq!(withdrawal_fee_bps(0, d, lo, hi), hi.min(10_000));
    }

    // ── Law 4: zero draw returns min_bps (clamped) ──

    #[kani::proof]
    fn zero_draw_returns_min() {
        let r: u128 = kani::any();
        kani::assume(r > 0);
        let (lo, hi): (u32, u32) = (kani::any(), kani::any());
        let hi_eff = hi.min(10_000);
        let lo_eff = lo.min(hi_eff);
        assert_eq!(withdrawal_fee_bps(r, 0, lo, hi), lo_eff);
    }

    // ── Law 5: full drain (draw >= reserve) returns max_bps (clamped) ──

    #[kani::proof]
    fn full_drain_returns_max() {
        let r: u128 = kani::any();
        kani::assume(r > 0);
        let d: u128 = kani::any();
        kani::assume(d >= r);
        let (lo, hi): (u32, u32) = (kani::any(), kani::any());
        assert_eq!(withdrawal_fee_bps(r, d, lo, hi), hi.min(10_000));
    }
}

/// ⭐ §BR-14 — the fee split conserves: the four pool credits sum to the fee exactly, each share is its floor, and the
/// remainder (< 1 atomic per share) lands in the surplus buffer — for EVERY u64 fee.
#[cfg(kani)]
mod fee_split_proofs {
    use crate::peg_arith::fee_split;

    fn law(split: fn(u64) -> (u64, u64, u64, u64), fee: u64) {
        let (st, bo, su, mi) = split(fee);
        let f = u128::from(fee);
        assert_eq!(u128::from(st) + u128::from(bo) + u128::from(su) + u128::from(mi), f, "the four credits sum to the fee");
        assert_eq!(u128::from(st), f * 4 / 10, "stakers take floor(40 %)");
        assert_eq!(u128::from(bo), f / 4, "bonders take floor(25 %)");
        assert_eq!(u128::from(mi), f / 10, "the miner pool takes floor(10 %)");
        assert!(u128::from(su) >= f / 4 && u128::from(su) <= f / 4 + 3, "the surplus takes 25 % plus the rounding");
    }

    #[kani::proof]
    fn fee_split_conserves_and_keeps_its_shares() {
        law(fee_split, kani::any());
    }

    /// REFUTATION: a split that drops the remainder (surplus = floor(25 %)) loses up to 3 atomic per credit.
    fn split_dropping_the_remainder(fee: u64) -> (u64, u64, u64, u64) {
        (fee / 10 * 4 + (fee % 10) * 4 / 10, fee / 4, fee / 4, fee / 10)
    }

    #[kani::proof]
    #[kani::should_panic]
    fn a_split_that_drops_the_remainder_is_caught() {
        law(split_dropping_the_remainder, kani::any());
    }
}

/// ⭐ §BR-11 — the miner payout rate never overdraws: paying the rate to every block of the next quarter, at the closed
/// quarter's block count, takes at most what that quarter credited, and the remainder kept is under one block's rate.
#[cfg(kani)]
mod miner_rate_proofs {
    use crate::peg_arith::miner_rate;

    fn law(rate: fn(u64, u64) -> u64, accrual: u64, blocks: u64) {
        // 64-bit checked arithmetic: a product past u64 already exceeds any u64 credit, so `None` IS the overdraw
        // (the 128-bit widening this replaced never finished in CBMC — 2 h on one harness, 2026-10-28).
        let r = rate(accrual, blocks);
        let n = blocks.max(1);
        let paid = r.checked_mul(n);
        assert!(matches!(paid, Some(p) if p <= accrual), "the quarter's payouts never exceed its credit");
        assert!(accrual - paid.unwrap() < n, "what stays in the pool is under one block's rounding");
    }

    #[kani::proof]
    fn miner_rate_never_overdraws() {
        law(miner_rate, kani::any(), kani::any());
    }

    /// REFUTATION: a rate that rounds UP overdraws the pool by up to one block's share.
    fn rate_rounding_up(accrual: u64, blocks: u64) -> u64 {
        accrual.div_ceil(blocks.max(1))
    }

    /// The refutation asks only the property the mutant breaks (the overdraw): a should_panic harness checks every property,
    /// and the remainder bound over a rounded-up rate is a 64-bit UNSAT search that never finished (2026-10-29, 48 min).
    #[kani::proof]
    #[kani::should_panic]
    fn a_rate_that_rounds_up_is_caught() {
        let (accrual, blocks): (u64, u64) = (kani::any(), kani::any());
        let n = blocks.max(1);
        let paid = rate_rounding_up(accrual, blocks).checked_mul(n);
        assert!(matches!(paid, Some(p) if p <= accrual), "the quarter's payouts never exceed its credit");
    }
}

/// ⭐ §BR-3 17.1 — the era-stepped split conserves at every era: the four credits sum to the fee, each share is its floor of
/// the era's percentage, and the miner's step is taken from the stakers' share alone.
#[cfg(kani)]
mod fee_split_era_proofs {
    use crate::peg_arith::fee_split_at;

    #[kani::proof]
    fn fee_split_at_conserves_at_every_era() {
        let fee: u64 = kani::any();
        let era: u64 = kani::any();
        let (st, bo, su, mi) = fee_split_at(fee, era);
        let f = u128::from(fee);
        let (sp, mp) = match era {
            0 | 1 => (40u128, 10u128),
            2 => (35, 15),
            _ => (30, 20),
        };
        assert_eq!(u128::from(st) + u128::from(bo) + u128::from(su) + u128::from(mi), f, "the four credits sum to the fee");
        assert_eq!(u128::from(st), f * sp / 100, "stakers take the era's floor share");
        assert_eq!(u128::from(mi), f * mp / 100, "the miner pool takes the era's floor share");
        assert_eq!(u128::from(bo), f / 4, "bonders take 25 % at every era");
        assert_eq!(sp + mp, 50, "the miner's step comes out of the stakers' share alone");
    }
}
